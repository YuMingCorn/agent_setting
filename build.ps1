# Generate the Codex and Gemini CLI versions of the agents, and the standard
# Agent Skills version of the portable skills, into .\portable\.
# Source of truth: .\agents\*.md and .\skills\<name>\ (Claude Code format).
# Never edit files under .\portable\ by hand; rerun this script instead.
# Usage: powershell -ExecutionPolicy Bypass -File .\build.ps1
# (Kept ASCII-only so Windows PowerShell 5.1 parses it under any code page.)

$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
$out  = Join-Path $repo 'portable'

# Skills that work outside Claude Code. brain stays Claude-only: it depends on
# Claude models, Claude-only frontmatter and the Claude agent team.
# session-review stays Claude-only: it reads Claude Code session transcripts.
$portableSkills = @('todo-review', 'wrap-up', 'restate', 'first-principle', 'reframe', 'sharpen')

# Claude Code tool name -> Gemini CLI tool names
$geminiTools = @{
    'Read'      = @('read_file')
    'Grep'      = @('grep_search')
    'Glob'      = @('glob', 'list_directory')
    'WebFetch'  = @('web_fetch')
    'WebSearch' = @('google_web_search')
    'Bash'      = @('run_shell_command')
}

$utf8 = New-Object Text.UTF8Encoding($false)

function Read-Text([string]$path) {
    return [IO.File]::ReadAllText($path, $utf8).Replace("`r`n", "`n")
}

function Write-Text([string]$path, [string]$text) {
    $dir = Split-Path $path -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }
    $text = $text.Replace("`r`n", "`n").TrimEnd("`n") + "`n"
    [IO.File]::WriteAllText($path, $text, $utf8)
}

# Split a Markdown file into simple "key: value" frontmatter and body.
function Read-Doc([string]$path) {
    $t = Read-Text $path
    if (-not $t.StartsWith("---`n")) { throw "$path does not start with frontmatter" }
    $end = $t.IndexOf("`n---`n", 4)
    if ($end -lt 0) { throw "$path has no closing frontmatter line" }
    $fm = [ordered]@{}
    foreach ($line in $t.Substring(4, $end - 4).Split("`n")) {
        if ($line -match '^([A-Za-z][\w-]*):\s*(.*)$') {
            $v = $Matches[2].Trim()
            if ($v.Length -ge 2 -and (($v[0] -eq '"' -and $v[-1] -eq '"') -or ($v[0] -eq "'" -and $v[-1] -eq "'"))) {
                $v = $v.Substring(1, $v.Length - 2)
            }
            $fm[$Matches[1]] = $v
        } elseif ($line.Trim()) {
            throw "$path has frontmatter this script cannot parse: $line"
        }
    }
    return @{ fm = $fm; body = $t.Substring($end + 5).Trim("`n") }
}

# A double-quoted string that is valid in both YAML and TOML.
function Format-Quoted([string]$s) {
    return '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Split-List([string]$s) {
    if (-not $s) { return @() }
    return @($s.Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_ })
}

if (Test-Path $out) { Remove-Item -Recurse -Force $out }

# ---- Agents ----
$agentFiles = Get-ChildItem (Join-Path $repo 'agents') -Filter '*.md' | Sort-Object Name
foreach ($f in $agentFiles) {
    $doc  = Read-Doc $f.FullName
    $name = $doc.fm['name']; $desc = $doc.fm['description']
    if (-not $name -or -not $desc) { throw "$($f.Name) needs name and description" }
    if ($doc.body.Contains("'''")) { throw "$($f.Name) body contains ''' and cannot go into a TOML literal string" }

    # Gemini CLI: Markdown + YAML. No tools line = all tools. No model = inherit.
    # Gemini agent names allow only lowercase letters, numbers, hyphens and underscores.
    $gName = $name.ToLowerInvariant()
    if ($gName -notmatch '^[a-z0-9_-]+$') { throw "$($f.Name): '$name' is not a valid Gemini agent name" }
    $g = @('---', "name: $gName","description: $(Format-Quoted $desc)", 'kind: local')
    $tools = Split-List $doc.fm['tools']
    if ($tools.Count -gt 0) {
        $g += 'tools:'
        $mapped = @()
        foreach ($tool in $tools) {
            if (-not $geminiTools.ContainsKey($tool)) { throw "$($f.Name): no Gemini mapping for tool '$tool'" }
            $mapped += $geminiTools[$tool]
        }
        foreach ($m in ($mapped | Select-Object -Unique)) { $g += "  - $m" }
    }
    $g += '---'
    Write-Text (Join-Path $out "gemini\agents\$gName.md") (($g -join "`n") + "`n" + $doc.body)

    # Codex: TOML. No model = inherit. Tool limits are not settable; the body says what not to do.
    $c = @(
        "# Generated by build.ps1 from agents/$($f.Name). Do not edit by hand.",
        "name = $(Format-Quoted $name)",
        "description = $(Format-Quoted $desc)",
        "developer_instructions = '''",
        $doc.body,
        "'''"
    )
    Write-Text (Join-Path $out "codex\agents\$name.toml") ($c -join "`n")
    Write-Host "Built agent $name"
}

# ---- Skills (Agent Skills standard: only name and description) ----
foreach ($s in $portableSkills) {
    $srcDir = Join-Path $repo "skills\$s"
    $dstDir = Join-Path $out "skills\$s"
    $doc = Read-Doc (Join-Path $srcDir 'SKILL.md')
    if ($doc.fm['name'] -ne $s) { throw "skills/$s/SKILL.md: name must equal the folder name" }
    if ($doc.fm['description'].Length -gt 1024) { throw "skills/$s/SKILL.md: description is over 1024 characters" }
    $sk = @('---', "name: $s", "description: $(Format-Quoted $doc.fm['description'])", '---')
    Write-Text (Join-Path $dstDir 'SKILL.md') (($sk -join "`n") + "`n`n" + $doc.body)
    Get-ChildItem $srcDir -Recurse -File | Where-Object { $_.Name -ne 'SKILL.md' } | ForEach-Object {
        $rel = $_.FullName.Substring($srcDir.Length + 1)
        Write-Text (Join-Path $dstDir $rel) (Read-Text $_.FullName)
    }
    Write-Host "Built skill $s"
}
